import express from 'express';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Server } from 'socket.io';
import { GameHub } from './game.js';
const __dirname=path.dirname(fileURLToPath(import.meta.url));
const app=express(); const server=http.createServer(app);
const io=new Server(server,{cors:{origin:true,credentials:false},maxHttpBufferSize:1e6});
const hub=new GameHub(io);
app.get('/health',(_req,res)=>res.json({ok:true,service:'casefile',rooms:hub.rooms.size}));
app.use(express.static(path.join(__dirname,'../dist')));
app.get('*',(req,res)=>res.sendFile(path.join(__dirname,'../dist/index.html')));
io.on('connection',socket=>{
 const buckets=new Map(); const allowed=(key,max,windowMs)=>{const now=Date.now(),a=(buckets.get(key)||[]).filter(t=>now-t<windowMs);if(a.length>=max)return false;a.push(now);buckets.set(key,a);return true;};
 socket.on('resume-session',({token}={})=>hub.resume(socket,token));
 socket.on('create-room',({name,token}={})=>hub.create(socket,name,token));
 socket.on('join-room',({code,name,token}={})=>hub.join(socket,code,name,token));
 socket.on('start-game',()=>hub.start(socket));
 socket.on('leave-room',()=>hub.leave(socket));
 socket.on('draw-stroke',stroke=>{if(allowed('draw',45,1000))hub.draw(socket,stroke);});
 socket.on('clear-drawing',()=>hub.clearDrawing(socket));
 socket.on('guess',text=>{if(allowed('guess',6,5000))hub.guess(socket,text);else socket.emit('notice',{type:'error',message:'Slow down—too many guesses.'});});
 socket.on('leave-room',()=>hub.leave(socket));
 socket.on('disconnect',()=>hub.disconnect(socket));
});
setInterval(()=>hub.hintTick(),1000).unref();
const port=Number(process.env.PORT)||3001;
server.listen(port,'0.0.0.0',()=>console.log(`Casefile server listening on ${port}`));
